-- Run once on a new Supabase project. Existing deployments should inspect their
-- table and policies first; do not recreate an active reviews table.
create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 60),
  service text not null check (service in ('Hijama','Homeopathy','Hijama & Homeopathy')),
  rating int not null check (rating between 1 and 5),
  review text not null check (char_length(review) between 10 and 700),
  approved boolean not null default false,
  created_at timestamptz not null default now()
);
alter table public.reviews enable row level security;
drop policy if exists "public can read approved reviews" on public.reviews;
create policy "public can read approved reviews" on public.reviews
for select to anon using (approved = true);
drop policy if exists "public can submit pending reviews" on public.reviews;
create policy "public can submit pending reviews" on public.reviews
for insert to anon with check (approved = false);
